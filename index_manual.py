"""Reproducible, offline provisional search index for the Himalayan owner's manual.

This builds dense TF-IDF/LSA vectors plus BM25 metadata. LSA is an offline baseline,
not a pretrained language embedding model. No answer is generated by this script.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import re
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pypdfium2 as pdfium


ROOT = Path(__file__).resolve().parent
DEFAULT_PDF = ROOT / "royal-enfield-new-himalayan-450-owners-manual-bs-six-english.pdf"
DEFAULT_OUT = ROOT / "provisional_index"
TOKEN_RE = re.compile(r"[a-z0-9]+(?:'[a-z0-9]+)?")
STOPWORDS = set(
    "a an and are as at be been but by can do for from has have if in into is it its "
    "of on or our should than that the their them there these this to was were when "
    "which while will with you your motorcycle royal enfield himalayan page".split()
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def normalize(raw: str) -> str:
    text = raw.replace("\ufffe", "").replace("\uf0a2", "- ").replace("\uf0ea", "- ")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t]+", " ", text)
    return "\n".join(line.strip() for line in text.splitlines() if line.strip())


def tokens(text: str) -> list[str]:
    return [term for term in TOKEN_RE.findall(text.lower()) if term not in STOPWORDS]


def page_metadata(text: str, page_number: int) -> tuple[int | None, str]:
    lines = text.splitlines()
    label = None
    if lines:
        match = re.match(r"(?:Royal Enfield Himalayan\s+(\d+)|(\d+)\s+Royal Enfield Himalayan)", lines[0])
        if match:
            label = int(match.group(1) or match.group(2))
    candidate = lines[1] if label is not None and len(lines) > 1 else (lines[0] if lines else "")
    section = candidate if candidate.isupper() and len(candidate) > 3 else "UNCLASSIFIED"
    return label, section


def extract_pages(pdf_path: Path) -> list[dict]:
    pdf = pdfium.PdfDocument(str(pdf_path))
    pages = []
    for index in range(len(pdf)):
        text = normalize(pdf[index].get_textpage().get_text_range())
        printed, section = page_metadata(text, index + 1)
        pages.append({
            "id": f"p{index + 1:04d}",
            "pdf_page": index + 1,
            "printed_page": printed,
            "section": section,
            "text": text,
            "word_count": len(tokens(text)),
        })
    return pages


def chunk_pages(pages: list[dict], max_words: int = 180) -> list[dict]:
    chunks = []
    for page in pages:
        lines = page["text"].splitlines()
        if page["printed_page"] is not None and lines:
            lines = lines[1:]
        if not lines:
            continue
        groups: list[list[str]] = []
        current: list[str] = []
        count = 0
        for line in lines:
            words = len(tokens(line))
            if current and count + words > max_words:
                groups.append(current)
                current, count = [], 0
            current.append(line)
            count += words
        if current:
            groups.append(current)
        for number, group in enumerate(groups, start=1):
            body = "\n".join(group)
            chunks.append({
                "id": f"{page['id']}c{number:02d}",
                "page_id": page["id"],
                "pdf_page": page["pdf_page"],
                "printed_page": page["printed_page"],
                "section": page["section"],
                "text": body,
                "word_count": len(tokens(body)),
                "contains_warning": bool(re.search(r"\b(?:WARNING|CAUTION)\b", body)),
            })
    return chunks


def graph_for(pages: list[dict], reviewed_links: list[dict]) -> dict:
    edges = []
    known = {p["id"] for p in pages}
    for left, right in zip(pages, pages[1:]):
        if left["section"] == right["section"] and left["section"] != "UNCLASSIFIED":
            edges.append({
                "from": left["id"], "to": right["id"],
                "type": "NEXT_PAGE_SAME_SECTION", "provenance": "contiguous pages with identical extracted section heading",
                "implies_procedure_order": False,
            })
    for link in reviewed_links:
        if link["from"] not in known or link["to"] not in known:
            raise ValueError(f"Graph link references a missing page: {link}")
        edges.append(link)
    return {
        "nodes": [{key: p[key] for key in ("id", "pdf_page", "printed_page", "section")} for p in pages],
        "edges": edges,
        "note": "Edges are navigation aids. Topic links do not establish a diagnostic dependency or OEM step order.",
    }


def save_json(path: Path, obj: object) -> None:
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def save_jsonl(path: Path, rows: list[dict]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as stream:
        for row in rows:
            stream.write(json.dumps(row, ensure_ascii=False) + "\n")


def build(pdf_path: Path, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    pages = extract_pages(pdf_path)
    chunks = chunk_pages(pages)
    if not chunks:
        raise ValueError("PDF extraction yielded no searchable chunks")

    doc_terms = [Counter(tokens(chunk["text"])) for chunk in chunks]
    df = Counter(term for counts in doc_terms for term in counts)
    vocab_terms = sorted((term for term, n in df.items() if n >= 2), key=lambda t: (-df[t], t))[:5000]
    vocab = {term: index for index, term in enumerate(vocab_terms)}
    n_docs = len(chunks)
    idf = np.array([math.log((1 + n_docs) / (1 + df[term])) + 1 for term in vocab_terms], dtype=np.float32)
    matrix = np.zeros((n_docs, len(vocab)), dtype=np.float32)
    for row, counts in enumerate(doc_terms):
        for term, frequency in counts.items():
            col = vocab.get(term)
            if col is not None:
                matrix[row, col] = (1 + math.log(frequency)) * idf[col]
    lengths = np.linalg.norm(matrix, axis=1, keepdims=True)
    matrix /= np.maximum(lengths, 1e-12)

    dimensions = min(96, n_docs - 1, len(vocab) - 1)
    if dimensions < 2:
        raise ValueError("Too little extracted text to construct dense vectors")
    rng = np.random.default_rng(42)
    probe = rng.standard_normal((len(vocab), dimensions + 12)).astype(np.float32)
    q, _ = np.linalg.qr(matrix @ probe, mode="reduced")
    _, _, vt = np.linalg.svd(q.T @ matrix, full_matrices=False)
    components = vt[:dimensions].astype(np.float32)
    vectors = (matrix @ components.T).astype(np.float32)
    vectors /= np.maximum(np.linalg.norm(vectors, axis=1, keepdims=True), 1e-12)

    links_path = ROOT / "reviewed_graph_links.json"
    reviewed_links = json.loads(links_path.read_text(encoding="utf-8")) if links_path.exists() else []
    graph = graph_for(pages, reviewed_links)
    save_jsonl(out / "pages.jsonl", pages)
    save_jsonl(out / "chunks.jsonl", chunks)
    save_json(out / "vocabulary.json", vocab_terms)
    save_json(out / "graph.json", graph)
    np.save(out / "idf.npy", idf)
    np.save(out / "components.npy", components)
    np.save(out / "embeddings.npy", vectors)
    save_json(out / "manifest.json", {
        "source_file": pdf_path.name,
        "source_sha256": sha256(pdf_path),
        "source_type": "owner_manual",
        "built_at_utc": datetime.now(timezone.utc).isoformat(),
        "pdf_pages": len(pages),
        "chunks": n_docs,
        "embedding_model": "local_tfidf_lsa_v1",
        "embedding_dimensions": dimensions,
        "embedding_limit": "Corpus-trained LSA baseline; not a pretrained semantic embedding model",
        "sparse_model": "BM25 computed at query time",
        "graph_nodes": len(graph["nodes"]),
        "graph_edges": len(graph["edges"]),
        "chunk_words_max": 180,
        "page_citation_policy": "Use pdf_page and printed_page; validate technical claims against original PDF page",
    })
    print(f"Indexed {len(pages)} PDF pages into {n_docs} chunks and {dimensions}-D vectors")
    print(f"Graph: {len(graph['nodes'])} page nodes, {len(graph['edges'])} edges")
    print(f"Output: {out}")


def load_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def rank(out: Path, query: str, limit: int) -> list[dict]:
    chunks = load_jsonl(out / "chunks.jsonl")
    vocab_terms = json.loads((out / "vocabulary.json").read_text(encoding="utf-8"))
    vocab = {term: i for i, term in enumerate(vocab_terms)}
    idf = np.load(out / "idf.npy")
    components = np.load(out / "components.npy")
    vectors = np.load(out / "embeddings.npy")
    counts = Counter(tokens(query))
    q = np.zeros(len(vocab), dtype=np.float32)
    for term, frequency in counts.items():
        col = vocab.get(term)
        if col is not None:
            q[col] = (1 + math.log(frequency)) * idf[col]
    if np.linalg.norm(q):
        q /= np.linalg.norm(q)
    dense = q @ components.T
    dense /= max(np.linalg.norm(dense), 1e-12)
    dense_scores = vectors @ dense

    postings: dict[str, dict[int, int]] = defaultdict(dict)
    lengths = []
    for i, chunk in enumerate(chunks):
        terms = Counter(tokens(chunk["text"]))
        lengths.append(sum(terms.values()))
        for term, frequency in terms.items():
            if term in counts:
                postings[term][i] = frequency
    average = sum(lengths) / len(lengths)
    sparse_scores = np.zeros(len(chunks), dtype=np.float32)
    for term, matches in postings.items():
        bm_idf = math.log(1 + (len(chunks) - len(matches) + 0.5) / (len(matches) + 0.5))
        for i, frequency in matches.items():
            sparse_scores[i] += bm_idf * frequency * 2.2 / (frequency + 1.2 * (0.25 + 0.75 * lengths[i] / average))
    dense_rank = np.argsort(-dense_scores)[:30]
    sparse_rank = np.argsort(-sparse_scores)[:30]
    fused = defaultdict(float)
    for rank, index in enumerate(dense_rank):
        fused[int(index)] += 1 / (60 + rank + 1)
    for rank, index in enumerate(sparse_rank):
        if sparse_scores[index] > 0:
            fused[int(index)] += 1 / (60 + rank + 1)
    results = []
    for index, score in sorted(fused.items(), key=lambda pair: -pair[1])[:limit]:
        chunk = chunks[index]
        results.append({
            "chunk_id": chunk["id"], "pdf_page": chunk["pdf_page"],
            "page_id": chunk["page_id"],
            "printed_page": chunk["printed_page"], "section": chunk["section"],
            "fused_score": round(score, 5), "dense_score": round(float(dense_scores[index]), 4),
            "bm25_score": round(float(sparse_scores[index]), 4),
            "excerpt": chunk["text"][:300].replace("\n", " "),
        })
    return results


def search(out: Path, query: str, limit: int) -> None:
    for result in rank(out, query, limit):
        print(json.dumps(result, ensure_ascii=False))


def validate(out: Path, gold_path: Path) -> None:
    manifest = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
    source_manifest = json.loads((ROOT / "source_manifest.json").read_text(encoding="utf-8"))
    pages = {row["id"]: row for row in load_jsonl(out / "pages.jsonl")}
    chunks = load_jsonl(out / "chunks.jsonl")
    vectors = np.load(out / "embeddings.npy")
    graph = json.loads((out / "graph.json").read_text(encoding="utf-8"))
    gold = json.loads(gold_path.read_text(encoding="utf-8"))
    cases = gold["cases"]
    errors = []
    if gold["source_sha256"].lower() != manifest["source_sha256"].lower():
        errors.append("Golden set and index use different PDF checksums")
    if source_manifest["sha256"].lower() != manifest["source_sha256"].lower():
        errors.append("Source manifest and index use different PDF checksums")
    source_path = ROOT / source_manifest["file"]
    if not source_path.exists() or sha256(source_path).lower() != manifest["source_sha256"].lower():
        errors.append("Current source PDF does not match the indexed checksum")
    if len({case["id"] for case in cases}) != len(cases):
        errors.append("Golden case IDs are not unique")
    if vectors.shape != (len(chunks), manifest["embedding_dimensions"]):
        errors.append("Embedding array shape does not match the manifest")
    if not np.isfinite(vectors).all():
        errors.append("Embedding array contains non-finite values")
    if len(graph["nodes"]) != len(pages):
        errors.append("Graph node count does not match page count")
    for case in cases:
        if not case.get("citations"):
            errors.append(f"{case['id']}: missing citations")
        for citation in case["citations"]:
            page = pages.get(citation["evidence_page_id"])
            if page is None or page["pdf_page"] != citation["pdf_page"] or page["printed_page"] != citation["printed_page"]:
                errors.append(f"{case['id']}: invalid citation {citation}")
    print(f"Validated {len(pages)} pages, {len(chunks)} chunks, {vectors.shape[1]}-D vectors, "
          f"{len(graph['edges'])} graph edges, and {len(cases)} Q&A cases")
    if errors:
        for error in errors:
            print("ERROR:", error)
        raise SystemExit(1)
    print("Structural citation and index checks passed; human source review is still required")


def export_gold(gold_path: Path, markdown_path: Path) -> None:
    gold = json.loads(gold_path.read_text(encoding="utf-8"))
    lines = [
        "# Provisional owner-manual reference answer cards",
        "",
        f"Source: [{gold['source_document']}]({gold['source_document']})",
        f"SHA-256: `{gold['source_sha256']}`",
        f"Status: `{gold['status']}`. These are source-linked answer/retrieval reference cards, not atomic dialogue entry prompts or a release-approved golden set.",
        "",
        "The primary provisional diagnostic golden set is [golden_dialogues.md](golden_dialogues.md). Some card questions here combine a symptom with a later observation; do not ask the rider to state that combination up front. The answers paraphrase the manual. PDF page numbers are one-based; printed numbers are the labels on the pages."
        " Do not use these answers as live advice without checking model applicability, source coverage, and warnings.",
        "",
    ]
    for case in gold["cases"]:
        lines.extend([
            f"## {case['id']} — {case['category'].replace('_', ' ').title()}",
            "",
            f"**Question:** {case['question']}",
            "",
            f"**Expected route:** `{case['expected_route']}`",
            "",
            f"**Grounded answer:** {case['gold_answer']}",
            "",
            "**Citations:** " + "; ".join(
                f"[PDF page {ref['pdf_page']}]({gold['source_document']}#page={ref['pdf_page']})"
                f" (printed page {ref['printed_page']}, `{ref['evidence_page_id']}`)"
                for ref in case["citations"]
            ),
            "",
        ])
    markdown_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Exported {len(gold['cases'])} Q&A cases to {markdown_path}")


def evaluate_retrieval(out: Path, gold_path: Path, report_path: Path) -> None:
    gold = json.loads(gold_path.read_text(encoding="utf-8"))
    rows = []
    for case in gold["cases"]:
        required = {ref["evidence_page_id"] for ref in case["citations"]}
        results = rank(out, case["question"], 10)
        top5 = {item["page_id"] for item in results[:5]}
        top10 = {item["page_id"] for item in results}
        rows.append({
            "case_id": case["id"],
            "required_pages": sorted(required),
            "top5_pages": [item["page_id"] for item in results[:5]],
            "top5_any": bool(required & top5),
            "top5_complete": required <= top5,
            "top10_complete": required <= top10,
        })
    n = len(rows)
    report = {
        "source_sha256": gold["source_sha256"],
        "index_model": "local_tfidf_lsa_v1_plus_bm25_rrf",
        "query_policy": "Gold question text only; no session context or graph expansion",
        "case_count": n,
        "top5_any_evidence_rate": sum(row["top5_any"] for row in rows) / n,
        "top5_complete_evidence_rate": sum(row["top5_complete"] for row in rows) / n,
        "top10_complete_evidence_rate": sum(row["top10_complete"] for row in rows) / n,
        "per_case": rows,
    }
    save_json(report_path, report)
    print(f"Top-5 any evidence: {sum(row['top5_any'] for row in rows)}/{n}")
    print(f"Top-5 complete evidence: {sum(row['top5_complete'] for row in rows)}/{n}")
    print(f"Top-10 complete evidence: {sum(row['top10_complete'] for row in rows)}/{n}")
    print(f"Report: {report_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    build_parser = sub.add_parser("build")
    build_parser.add_argument("--pdf", type=Path, default=DEFAULT_PDF)
    build_parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    search_parser = sub.add_parser("search")
    search_parser.add_argument("query")
    search_parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    search_parser.add_argument("--limit", type=int, default=5)
    validate_parser = sub.add_parser("validate")
    validate_parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    validate_parser.add_argument("--gold", type=Path, default=ROOT / "golden_qa.json")
    export_parser = sub.add_parser("export-gold")
    export_parser.add_argument("--gold", type=Path, default=ROOT / "golden_qa.json")
    export_parser.add_argument("--markdown", type=Path, default=ROOT / "golden_qa.md")
    eval_parser = sub.add_parser("evaluate")
    eval_parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    eval_parser.add_argument("--gold", type=Path, default=ROOT / "golden_qa.json")
    eval_parser.add_argument("--report", type=Path, default=ROOT / "provisional_index" / "retrieval_baseline.json")
    args = parser.parse_args()
    if args.command == "build":
        build(args.pdf, args.out)
    elif args.command == "search":
        search(args.out, args.query, args.limit)
    elif args.command == "validate":
        validate(args.out, args.gold)
    elif args.command == "export-gold":
        export_gold(args.gold, args.markdown)
    else:
        evaluate_retrieval(args.out, args.gold, args.report)


if __name__ == "__main__":
    main()
